import mongoose from 'mongoose';

const ratingDistributionSchema = new mongoose.Schema(
  {
    rating: Number, // 1 to 5
    count: Number,
    percentage: Number
  },
  { _id: false }
);

const categoryScoreSchema = new mongoose.Schema(
  {
    category: String,
    averageRating: Number,
    totalResponses: Number,
    distribution: [ratingDistributionSchema]
  },
  { _id: false }
);

const facultyReportSchema = new mongoose.Schema(
  {
    campaign: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'FeedbackCampaign',
      required: true,
      index: true
    },
    faculty: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'FacultyProfile',
      required: true,
      index: true
    },
    reportingPeriod: {
      type: String,
      required: true // e.g. "Fall 2024" or "2024-2025 Semester 1"
    },
    version: {
      type: Number,
      default: 1
    },
    status: {
      type: String,
      enum: ['pending', 'generating', 'completed', 'insufficient_data', 'failed'],
      default: 'pending',
      index: true
    },
    // Quantitative stats computed deterministically on server
    quantitativeStats: {
      totalEligibleStudents: { type: Number, default: 0 },
      totalResponses: { type: Number, default: 0 },
      responseRatePercentage: { type: Number, default: 0 },
      overallAverageRating: { type: Number, default: 0 },
      ratingDistribution: [ratingDistributionSchema],
      categoryScores: [categoryScoreSchema]
    },
    // Qualitative synthesis generated by OpenAI
    qualitativeSynthesis: {
      executiveSummary: { type: String },
      teachingStrengths: [{ type: String }],
      improvementOpportunities: [{ type: String }],
      recurringThemes: [
        {
          theme: String,
          description: String,
          sentiment: { type: String, enum: ['positive', 'neutral', 'constructive'] }
        }
      ],
      studentSentimentSummary: { type: String },
      actionableRecommendations: [{ type: String }],
      evidenceSummaries: [{ type: String }],
      limitations: [{ type: String }]
    },
    aiMetadata: {
      modelUsed: { type: String },
      tokensUsed: { type: Number },
      generationLatencyMs: { type: Number },
      confidenceScore: { type: String, enum: ['high', 'medium', 'low', 'insufficient'] }
    },
    errorMessage: {
      type: String
    },
    generatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User'
    },
    pdfFilePath: {
      type: String
    },
    generatedAt: {
      type: Date
    }
  },
  {
    timestamps: true
  }
);

facultyReportSchema.index({ campaign: 1, faculty: 1, version: 1 }, { unique: true });

export const FacultyReport = mongoose.model('FacultyReport', facultyReportSchema);
